  let lang = localStorage.getItem(STORAGE_KEY) || "ru";
  if (!DICT[lang]) lang = "ru";

  function t(key, vars) {
    let s = (DICT[lang] && DICT[lang][key]) || (DICT.ru && DICT.ru[key]) || key;
    if (vars) {
      Object.keys(vars).forEach((k) => {
        s = s.replace(new RegExp("\\{" + k + "\\}", "g"), String(vars[k]));
      });
    }
    return s;
  }

  function getLang() {
    return lang;
  }

  function setLang(next) {
    if (!DICT[next]) return;
    lang = next;
    localStorage.setItem(STORAGE_KEY, lang);
    applyDom();
  }

  function applyDom(root) {
    const scope = root || document;
    scope.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (key) el.textContent = t(key);
    });
    scope.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (key) el.setAttribute("placeholder", t(key));
    });
    scope.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      const key = el.getAttribute("data-i18n-aria");
      if (key) el.setAttribute("aria-label", t(key));
    });
    const authSel = document.getElementById("lang-auth");
    const appSel = document.getElementById("lang-app");
    if (authSel) authSel.value = lang;
    if (appSel) appSel.value = lang;
    document.documentElement.lang = lang === "kk" ? "kk" : lang;
    document.title = t("brand");
  }

