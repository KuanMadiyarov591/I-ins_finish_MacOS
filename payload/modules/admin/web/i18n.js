  let lang = localStorage.getItem("ins_lang") || "ru";
  if (!dict[lang]) lang = "ru";

  function setLang(next) {
    if (!dict[next]) return;
    lang = next;
    localStorage.setItem("ins_lang", lang);
    document.documentElement.lang = lang === "kk" ? "kk" : lang;
  }

  function t(key) {
    const pack = dict[lang] || dict.ru;
    return pack[key] != null ? pack[key] : dict.ru[key] || key;
  }

  function statusLabel(s) {
    const map = {
      Pending: "st_pending",
      Approved: "st_approved",
      Disapproved: "st_disapproved",
      Paid: "st_paid",
      Due: "st_due",
      Overdue: "st_overdue",
      Active: "st_active",
      Answered: "st_answered",
      Rejected: "st_rejected",
      Settled: "st_settled",
    };
    return map[s] ? t(map[s]) : s;
  }

  function displayFirstName(fullName, username) {
    const raw = (fullName || "").trim();
    if (!raw) return username || "";
    return raw.split(/\s+/)[0];
  }

  function applyStatic() {
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (key) el.textContent = t(key);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (key) el.setAttribute("placeholder", t(key));
    });
    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
      const key = el.getAttribute("data-i18n-title");
      if (key) el.setAttribute("title", t(key));
    });
    const sel = document.getElementById("lang-select");
    if (sel) sel.value = lang;
    const selAuth = document.getElementById("lang-select-auth");
    if (selAuth) selAuth.value = lang;
  }

